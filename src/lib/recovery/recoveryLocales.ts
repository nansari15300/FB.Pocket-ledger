const LANG_KEY = "pl_recovery_lang_v1";

export function readRecoveryLang(): RecoveryLang {
  try {
    const v = typeof window !== "undefined" ? window.localStorage.getItem(LANG_KEY) : null;
    return v === "hi" || v === "ne" || v === "en" ? v : "en";
  } catch {
    return "en";
  }
}

export function writeRecoveryLang(lang: RecoveryLang): void {
  try {
    window.localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* ignore */
  }
}
